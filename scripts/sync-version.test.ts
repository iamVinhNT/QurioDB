    expect(workflow.slice(windowsSmokeIndex, windowsTauriIndex)).toContain("taskkill");
    expect(linuxSmokeIndex).toBeGreaterThanOrEqual(0);
    expect(linuxSmokeIndex).toBeLessThan(linuxTauriIndex);
