describe("CLI Boundary and Subprocess Execution", () => {
  const syncScriptPath = path.join(process.cwd(), "scripts/sync-version.ts");

  it("CLI exits 1 with error when .env is missing in fixture root", () => {
    const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), "quriodb-cli-noenv-"));
    const proc = Bun.spawnSync(["bun", syncScriptPath], {
      cwd: tempDir,
    });
    expect(proc.exitCode).toBe(1);
    const stderr = proc.stderr.toString();
    expect(stderr).toContain("Canonical environment file not found");
    fs.rmSync(tempDir, { recursive: true, force: true });
  });

  it("CLI exits 1 when QURIODB_VERSION is malformed (1.2 or v1.2.3)", () => {
    const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), "quriodb-cli-malformed-"));
    fs.writeFileSync(path.join(tempDir, ".env"), "QURIODB_VERSION=1.2\n");
    const proc1 = Bun.spawnSync(["bun", syncScriptPath], {
      cwd: tempDir,
    });
    expect(proc1.exitCode).toBe(1);
    expect(proc1.stderr.toString()).toContain("Invalid semantic version: '1.2'");

    fs.writeFileSync(path.join(tempDir, ".env"), "QURIODB_VERSION=v1.2.3\n");
    const proc2 = Bun.spawnSync(["bun", syncScriptPath], {
      cwd: tempDir,
    });
    expect(proc2.exitCode).toBe(1);
    expect(proc2.stderr.toString()).toContain("Invalid semantic version: 'v1.2.3'");
    fs.rmSync(tempDir, { recursive: true, force: true });
  });

  it("CLI --check prints every stale path and exits 1 on mismatch", () => {
    const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), "quriodb-cli-stale-"));
    fs.writeFileSync(path.join(tempDir, ".env"), "QURIODB_VERSION=2.0.0\n");

    fs.mkdirSync(path.join(tempDir, "apps/desktop/src-tauri"), { recursive: true });
    fs.writeFileSync(
      path.join(tempDir, "apps/desktop/package.json"),
      JSON.stringify({ name: "desktop", version: "0.1.0" }, null, 2),
    );
    fs.writeFileSync(
      path.join(tempDir, "apps/desktop/src-tauri/tauri.conf.json"),
      JSON.stringify({ productName: "QurioDB", version: "0.1.0" }, null, 2),
    );
    fs.writeFileSync(
      path.join(tempDir, "apps/desktop/src-tauri/Cargo.toml"),
      '[package]\nname = "quriodb-desktop"\nversion = "0.1.0"\n',
    );
    fs.writeFileSync(
      path.join(tempDir, "apps/desktop/src-tauri/Cargo.lock"),
      '[[package]]\nname = "quriodb-desktop"\nversion = "0.1.0"\n',
    );
    fs.writeFileSync(
      path.join(tempDir, "README.md"),
      "- [Download Windows Installer (v0.1.0)](https://github.com/trungvinh2102/QurioDB/releases/download/v0.1.0/QurioDB_0.1.0_x64_en-US.msi)\n- [Download Windows Setup (v0.1.0)](https://github.com/trungvinh2102/QurioDB/releases/download/v0.1.0/QurioDB_0.1.0_x64-setup.exe)\n- [Download Linux Package (v0.1.0)](https://github.com/trungvinh2102/QurioDB/releases/download/v0.1.0/QurioDB_0.1.0_amd64.deb)\n- [Download Linux AppImage (v0.1.0)](https://github.com/trungvinh2102/QurioDB/releases/download/v0.1.0/QurioDB_0.1.0_amd64.AppImage)\nQurioDB - v0.1.0\n",
    );
    fs.writeFileSync(path.join(tempDir, "apps/desktop/README.md"), "_QurioDB Team - v0.1.0_\n");

    const checkProc = Bun.spawnSync(["bun", syncScriptPath, "--check"], {
      cwd: tempDir,
    });
    expect(checkProc.exitCode).toBe(1);
    const stderr = checkProc.stderr.toString();
    expect(stderr).toContain("Version mismatch detected! Canonical QURIODB_VERSION=2.0.0");
    expect(stderr).toContain("apps/desktop/package.json");
    expect(stderr).toContain("apps/desktop/src-tauri/tauri.conf.json");
    expect(stderr).toContain("apps/desktop/src-tauri/Cargo.toml");
    expect(stderr).toContain("apps/desktop/src-tauri/Cargo.lock");
    expect(stderr).toContain("README.md");
    expect(stderr).toContain("apps/desktop/README.md");

    const syncProc = Bun.spawnSync(["bun", syncScriptPath], {
      cwd: tempDir,
    });
    expect(syncProc.exitCode).toBe(0);

    const checkProcAfter = Bun.spawnSync(["bun", syncScriptPath, "--check"], {
      cwd: tempDir,
    });
    expect(checkProcAfter.exitCode).toBe(0);
    expect(checkProcAfter.stdout.toString()).toContain("All managed targets match QURIODB_VERSION=2.0.0");

    fs.rmSync(tempDir, { recursive: true, force: true });
  });
});

