describe("Version validation and parsing", () => {
  it("parses valid QURIODB_VERSION from env string", () => {
    const envContent = "FOO=bar\nQURIODB_VERSION=1.2.3\nBAZ=qux";
    expect(parseVersionFromEnv(envContent)).toBe("1.2.3");
  });

  it("handles whitespace and quotes in env file", () => {
    expect(parseVersionFromEnv('QURIODB_VERSION="1.2.3"')).toBe("1.2.3");
    expect(parseVersionFromEnv("QURIODB_VERSION='1.2.3'")).toBe("1.2.3");
    expect(parseVersionFromEnv("  QURIODB_VERSION = 1.2.3  ")).toBe("1.2.3");
  });

  it("throws error when QURIODB_VERSION is missing", () => {
    expect(() => parseVersionFromEnv("FOO=bar")).toThrow(
      "Missing QURIODB_VERSION in environment configuration",
    );
  });

  it("throws error on malformed semver 1.2 or prefixed v1.2.3", () => {
    expect(() => validateSemver("1.2")).toThrow("Invalid semantic version: '1.2'");
    expect(() => validateSemver("v1.2.3")).toThrow("Invalid semantic version: 'v1.2.3'");
    expect(() => validateSemver("1.2.3.4")).toThrow("Invalid semantic version: '1.2.3.4'");
    expect(() => validateSemver("latest")).toThrow("Invalid semantic version: 'latest'");
    expect(() => validateSemver("")).toThrow("Invalid semantic version: ''");
  });

  it("validates standard semantic versions", () => {
    expect(validateSemver("0.1.0")).toBe("0.1.0");
    expect(validateSemver("1.2.3")).toBe("1.2.3");
    expect(validateSemver("1.0.0-alpha.1")).toBe("1.0.0-alpha.1");
    expect(validateSemver("2.0.0-rc.2+build.123")).toBe("2.0.0-rc.2+build.123");
  });
});

